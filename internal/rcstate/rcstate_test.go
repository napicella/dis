var now = time.Date(2026, 10, 2, 11, 0, 0, 0, time.UTC)

func newStore(t *testing.T) (*Store, *bytes.Buffer) {
	t.Helper()
	root := t.TempDir()
	var warn bytes.Buffer
	return &Store{
		StatePath: filepath.Join(root, "share", "sections.yaml"),
		Dir:       filepath.Join(root, "rc", "configs-generated"),
		Warn:      &warn,
		Now:       func() time.Time { return now },
	}, &warn
}

func write(t *testing.T, path, content string) {
	t.Helper()
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
		t.Fatal(err)
	}
}

func read(t *testing.T, path string) string {
	t.Helper()
	b, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	return string(b)
}

func names(secs []Section) []string {
	var out []string
	for _, s := range secs {
		out = append(out, s.Name)
	}
	return out
}

func upsert(file string, sec Section) func(*State) error {
	return func(st *State) error { return st.Upsert(file, sec) }
}

func TestUpsertKeepsOrder(t *testing.T) {
	st := newState()
	for _, n := range []string{"A", "B", "C"} {
		if err := st.Upsert("bash_paths", Section{Name: n, Content: "old"}); err != nil {
			t.Fatal(err)
		}
	}
	if err := st.Upsert("bash_paths", Section{Name: "A", Owner: "p", Content: "new"}); err != nil {
		t.Fatal(err)
	}
	secs := st.Files["bash_paths"]
	if got := names(secs); !reflect.DeepEqual(got, []string{"A", "B", "C"}) {
		t.Errorf("order = %v", got)
	}
	if secs[0] != (Section{Name: "A", Owner: "p", Content: "new"}) {
		t.Errorf("A = %+v", secs[0])
	}
}

func TestLocks(t *testing.T) {
	st := newState()
	locked := Section{Name: "ls", Owner: "common/eza", Locked: true, Content: "alias ls=eza"}
	if err := st.Upsert("bash_aliases", locked); err != nil {
		t.Fatal(err)
	}
	if err := st.Upsert("bash_aliases", Section{Name: "ls", Owner: "other", Content: "x"}); !errors.Is(err, ErrLocked) {
		t.Errorf("upsert by another owner: err = %v", err)
	}
	if err := st.Remove("bash_aliases", "ls", "other"); !errors.Is(err, ErrLocked) {
		t.Errorf("remove by another owner: err = %v", err)
	}
	if st.Files["bash_aliases"][0] != locked {
		t.Errorf("locked section changed: %+v", st.Files["bash_aliases"][0])
	}
	if err := st.Upsert("bash_aliases", Section{Name: "ls", Owner: "common/eza", Locked: true, Content: "y"}); err != nil {
		t.Errorf("upsert by the owner: %v", err)
	}
	if err := st.Remove("bash_aliases", "ls", "common/eza"); err != nil || len(st.Files["bash_aliases"]) != 0 {
		t.Errorf("remove by the owner: %v, %+v", err, st.Files["bash_aliases"])
	}
	if err := st.Remove("bash_aliases", "ls", ""); err != nil {
		t.Errorf("remove absent: %v", err)
	}
}

